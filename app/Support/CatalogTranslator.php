    public static function toItalian(?string $text): ?string
    {
        if ($text === null || $text === '') {
            return $text;
        }

        self::boot();

        $out = $text;

        foreach (self::$phrases as $pt => $it) {
            $out = str_ireplace($pt, $it, $out);
        }

        // Remplacement de mots entiers (accents / casse respectés autant que possible).
        $out = preg_replace_callback(
            '/\b[\p{L}][\p{L}\']*\b/u',
            function (array $m): string {
                $word = $m[0];
                $lower = mb_strtolower($word, 'UTF-8');
                if (! isset(self::$words[$lower])) {
                    return $word;
                }
                $it = self::$words[$lower];

                // Conserver MAJUSCULES / Title Case
                if ($word === mb_strtoupper($word, 'UTF-8')) {
                    return mb_strtoupper($it, 'UTF-8');
                }
                if (mb_strtoupper(mb_substr($word, 0, 1, 'UTF-8'), 'UTF-8') === mb_substr($word, 0, 1, 'UTF-8')
                    && mb_strtolower(mb_substr($word, 1, null, 'UTF-8'), 'UTF-8') === mb_substr($word, 1, null, 'UTF-8')) {
                    return mb_strtoupper(mb_substr($it, 0, 1, 'UTF-8'), 'UTF-8').mb_substr($it, 1, null, 'UTF-8');
                }

                return $it;
            },
            $out
        );

        return $out;
    }

    /**
     * @return array{pt: string, it: string}|null
     */
    public static function bilingual(?string $text): ?array
    {
        if ($text === null) {
            return null;
        }

        return [
            'pt' => $text,
            'it' => self::toItalian($text) ?? $text,
        ];
    }

    /**
     * Accepte string|array déjà bilingue et normalise en {pt, it}.
     *
     * @return array{pt: string, it: string}|null
     */
    public static function normalize(mixed $value, bool $force = false): ?array
    {
        if ($value === null) {
            return null;
        }

        if (is_array($value)) {
            $pt = (string) ($value['pt'] ?? $value['PT'] ?? reset($value) ?: '');
            $it = $force
                ? (string) (self::toItalian($pt) ?? $pt)
                : (string) ($value['it'] ?? $value['IT'] ?? self::toItalian($pt) ?? $pt);

            return ['pt' => $pt, 'it' => $it];
        }

        return self::bilingual((string) $value);
    }

    /**
     * Traduit les libellés visibles des variations (options + name) pour la locale courante.
     * Ne touche pas aux chemins d'images ni aux clés techniques.
     *
     * @param  array<string, mixed>  $variations
     * @return array<string, mixed>
     */
    public static function translateVariationsTree(array $variations, ?string $locale = null): array
    {
        $locale = $locale ?? app()->getLocale();
        if ($locale === 'pt') {
            return $variations;
        }

        // Garder les clés d'options (COR, MEDIDA…) inchangées — le JS les compare en dur.
        // On ne traduit que les libellés affichés (opt.name).
        if (! empty($variations['variations']) && is_array($variations['variations'])) {
            foreach ($variations['variations'] as &$row) {
                if (! is_array($row)) {
                    continue;
                }
                foreach ($row as &$opt) {
                    if (! is_array($opt) || ! isset($opt['name']) || ! is_string($opt['name'])) {
                        continue;
                    }
                    $name = $opt['name'];
                    // Ne pas traduire les chemins d'images / URLs
                    if ($name === '' || str_contains($name, '/') || preg_match('/\.(jpe?g|png|webp|avif|gif)(\?|$)/i', $name)) {
                        continue;
                    }
                    $opt['name'] = self::toItalian($name) ?? $name;
                }
                unset($opt);
            }
            unset($row);
        }

        return $variations;
    }

